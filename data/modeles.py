def _octaedre(r=14, cy=-25):
    haut, bas = (0, cy - r, 0), (0, cy + r, 0)
    eq = [(r, cy, 0), (0, cy, r), (-r, cy, 0), (0, cy, -r)]
    seg = []
    for i in range(4):
        seg.append((haut, eq[i]))
        seg.append((bas, eq[i]))
        seg.append((eq[i], eq[(i + 1) % 4]))
    return seg


def _croix(arm=14, ep=5, prof=4, cy=-25):
    # contour d'une croix "+" extrudée en 3D
    c = [(ep, -arm), (ep, -ep), (arm, -ep), (arm, ep), (ep, ep), (ep, arm),
         (-ep, arm), (-ep, ep), (-arm, ep), (-arm, -ep), (-ep, -ep), (-ep, -arm)]
    seg = []
    for i in range(len(c)):
        a, b = c[i], c[(i + 1) % len(c)]
        for z in (-prof, prof):
            seg.append(((a[0], cy + a[1], z), (b[0], cy + b[1], z)))
        seg.append(((a[0], cy + a[1], -prof), (a[0], cy + a[1], prof)))
    return seg


